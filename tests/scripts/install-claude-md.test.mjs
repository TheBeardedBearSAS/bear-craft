import { describe, it, expect, afterAll } from 'vitest';
import { execSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';

const PROJECT_ROOT = path.resolve(import.meta.dirname, '../..');
const SCRIPTS_DIR = path.join(PROJECT_ROOT, 'Dev/scripts');
const PROJECT_SCRIPT = path.join(PROJECT_ROOT, 'Project/install-project-commands.sh');
const LANGS = ['en', 'fr', 'es', 'de', 'pt'];

const tmpDirs = [];

function makeProjectDir(name) {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'cc-test-claude-md-'));
  tmpDirs.push(base);
  const dir = path.join(base, name);
  fs.mkdirSync(dir);
  return dir;
}

afterAll(() => {
  for (const dir of tmpDirs) {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

// #269 : `--tech=symfony` installait un .claude/CLAUDE.md générique (« MyProject », « Pest 4 »)
// et un CLAUDE.md racine dont les titres portaient les namespaces supprimés /project: et /gate:.
describe('.claude/CLAUDE.md generated by the tech installers', { timeout: 60000 }, () => {
  it('uses the project directory name and the stack testing framework, not a generic placeholder', () => {
    const dir = makeProjectDir('urssaf-mock');
    execSync(`bash "${path.join(SCRIPTS_DIR, 'install-symfony-rules.sh')}" --lang=en --plugin-mode "${dir}"`, {
      encoding: 'utf8',
    });
    const md = fs.readFileSync(path.join(dir, '.claude/CLAUDE.md'), 'utf8');

    expect(md).toContain('# urssaf-mock - Symfony Project');
    expect(md).not.toContain('MyProject');
    expect(md).toMatch(/PHPUnit/);
    expect(md).not.toContain('Pest 4');
    expect(md).toContain('**Stack**: Symfony 8.1, PHP 8.4+');
    expect(md).toContain('**Tests**: PHPUnit (or Pest) + Behat + Infection');
    expect(md).not.toContain('Codeception');
    expect(md).not.toMatch(/\*\*Tests\*\*: \*\*/);
  });

  it('keeps an explicit PROJECT_NAME when provided', () => {
    const dir = makeProjectDir('whatever');
    execSync(
      `PROJECT_NAME="Acme" bash "${path.join(SCRIPTS_DIR, 'install-symfony-rules.sh')}" --lang=en --plugin-mode "${dir}"`,
      {
        encoding: 'utf8',
      }
    );
    expect(fs.readFileSync(path.join(dir, '.claude/CLAUDE.md'), 'utf8')).toContain('# Acme - Symfony Project');
  });
});

describe('root CLAUDE.md generated by install-project-commands.sh', { timeout: 60000 }, () => {
  it.each(LANGS)('has no removed /project: or /gate: namespace (lang=%s)', (lang) => {
    const dir = makeProjectDir('proj');
    execSync(`bash "${PROJECT_SCRIPT}" --lang=${lang} --tech=symfony --plugin-mode "${dir}"`, { encoding: 'utf8' });
    const md = fs.readFileSync(path.join(dir, 'CLAUDE.md'), 'utf8');

    expect(md).not.toMatch(/\/(project|gate):/);
  });
});
